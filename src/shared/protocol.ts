// The wire protocol — the ONLY place messages are defined (CLAUDE.md §5).
// Every message is a Valibot schema; TypeScript types are derived from the schemas, never
// written separately. The server validates every incoming message with these schemas; the
// client imports TYPES only (`import type`, lint-enforced) so schemas stay out of the bundle.
//
// Type honesty (Phase 2 review): ids are BRANDED (a PlayerId can't be passed where a ConnId is
// expected), and messages that have several shapes are VARIANTS (a snapshot in the LOBBY has no
// round; results without a ranking have no reveal steps) — impossible states don't type-check.
import * as v from 'valibot';
import { AVATAR_PRESET_IDS } from './avatars';
import { DRINK_ACTIONS, MAX_SIPS } from './drinkRules';
import { ADD_ON_CATEGORY_IDS, CATEGORY_IDS } from './questionCategories';
import { LABEL_SET_IDS } from './questionLabels';
import { GAME_MODES } from './spots';
import {
  GAME_KEY_ALPHABET,
  GAME_KEY_LENGTH,
  GAME_LENGTHS,
  MAX_PLAYERS,
  NICKNAME_MAX_INPUT_CHARS,
  QUESTION_MAX_LENGTH,
} from './constants';

// ── Primitives ──────────────────────────────────────────────────────────────

/** Random server-generated ids (players, game instances, reclaim requests): 12 base62 chars. */
export const ID_LENGTH = 12;
/** The id format without anchors — also used to build the Worker's URL routes. */
export const ID_SOURCE = `[0-9A-Za-z]{${String(ID_LENGTH)}}`;
const ID_PATTERN = new RegExp(`^${ID_SOURCE}$`);

export const PlayerIdSchema = v.pipe(v.string(), v.regex(ID_PATTERN), v.brand('PlayerId'));
export const GameIdSchema = v.pipe(v.string(), v.regex(ID_PATTERN), v.brand('GameId'));
export const RequestIdSchema = v.pipe(v.string(), v.regex(ID_PATTERN), v.brand('RequestId'));
/** Socket id, generated by the Durable Object (not by the engine). */
export const ConnIdSchema = v.pipe(v.string(), v.minLength(1), v.maxLength(64), v.brand('ConnId'));

export const GameKeySchema = v.pipe(
  v.string(),
  v.regex(new RegExp(`^[${GAME_KEY_ALPHABET}]{${GAME_KEY_LENGTH}}$`)),
  v.brand('GameKey'),
);

/** Phone-generated token, 128+ bits, base64url or hex. Only ever travels phone → server. */
export const TokenSchema = v.pipe(v.string(), v.regex(/^[A-Za-z0-9_-]{22,64}$/));

/** Server epoch milliseconds. All times on the wire use this (CLAUDE.md §5). */
export const TimestampSchema = v.pipe(v.number(), v.integer(), v.minValue(0));

/** Raw nickname input — length is checked loosely here; `validateNickname` is the real rule. */
export const NicknameInputSchema = v.pipe(
  v.string(),
  v.minLength(1),
  v.maxLength(NICKNAME_MAX_INPUT_CHARS), // generous: graphemes can be many code units
);

/** One of the ready-made avatars (shared/avatars.ts) — ids are never removed or renamed. */
export const PresetIdSchema = v.picklist(AVATAR_PRESET_IDS);

export const GameLengthSchema = v.picklist(GAME_LENGTHS);

/** Question category (Q-7) — ids are never renamed or removed (shared/questionCategories.ts). */
export const CategoryIdSchema = v.picklist(CATEGORY_IDS);

/** A category the host can add to the always-on Default one (G-22). */
export const AddOnCategoryIdSchema = v.picklist(ADD_ON_CATEGORY_IDS);

/** The chosen add-ons (G-22): any of them, possibly none — Default is always played. No duplicates. */
export const CategoriesSchema = v.pipe(
  v.array(AddOnCategoryIdSchema),
  v.check((ids) => new Set(ids).size === ids.length, 'Duplicate category'),
);

/** Spotlight (rank everyone shown) or Podium (everyone shown, fill the top 3) — G-24. */
export const GameModeSchema = v.picklist(GAME_MODES);

/** Label set naming the spot / reveal words (Q-8, shared/questionLabels.ts). */
export const LabelSetIdSchema = v.picklist(LABEL_SET_IDS);

/** The host's lobby settings (G-20, G-22, G-24) — locked at Start. */
export const SettingsSchema = v.strictObject({
  gameLength: GameLengthSchema,
  categories: CategoriesSchema,
  mode: GameModeSchema,
});

export const RoundIdSchema = v.pipe(v.number(), v.integer(), v.minValue(1));

// ── Shared building blocks ──────────────────────────────────────────────────

/** presetId always exists (shown while a photo loads); photoVersion is set only by the server. */
export const AvatarSchema = v.strictObject({
  presetId: PresetIdSchema,
  photoVersion: v.nullable(v.pipe(v.number(), v.integer(), v.minValue(1))),
});

export const PhaseSchema = v.picklist(['LOBBY', 'QUESTION', 'RESULTS', 'ENDED']);
export const EndReasonSchema = v.picklist(['finished', 'hostEnded', 'updated']);
export const PlayerStatusSchema = v.picklist(['active', 'left', 'removed']);

/** What every phone may know about a player. No token data, ever. */
export const PublicPlayerSchema = v.strictObject({
  playerId: PlayerIdSchema,
  nickname: v.string(),
  avatar: AvatarSchema,
  status: PlayerStatusSchema,
  online: v.boolean(),
  /** For the host's remove button (G-43: offline ≥ 2 min) and "Offline" labels. */
  offlineSince: v.nullable(TimestampSchema),
  // No "waiting for the next round" flag: phones derive it from the round's participants
  // (shared/ready.ts isWaitingForNextRound) — a per-player flag goes stale with every roundStarted.
});

/**
 * A question as stored in a game and sent to phones (Q-2). `labels` is always present here; the
 * bank file may omit it (game/questions.ts defaults it to 'likely').
 */
export const QuestionSchema = v.strictObject({
  id: v.pipe(v.string(), v.minLength(1)),
  text: v.pipe(v.string(), v.minLength(1), v.maxLength(QUESTION_MAX_LENGTH)),
  category: CategoryIdSchema,
  labels: LabelSetIdSchema,
});

/** A running round as phones see it (no answers — only who is ready). */
export const PublicRoundSchema = v.strictObject({
  roundId: RoundIdSchema,
  /** 1-based question number ("7 / 25"). */
  number: v.pipe(v.number(), v.integer(), v.minValue(1)),
  total: GameLengthSchema,
  question: QuestionSchema,
  /** Players to rank (G-34): up to MAX_CANDIDATES in Spotlight, everyone in Podium. */
  candidates: v.pipe(v.array(PlayerIdSchema), v.minLength(1), v.maxLength(MAX_PLAYERS)),
  /**
   * How many places each voter fills (G-24, shared/spots.ts): = candidates in Spotlight, the top 3
   * in Podium. Fewer spots than candidates = a partial ranking ("No votes" group, no bottom step).
   */
  spots: v.pipe(v.number(), v.integer(), v.minValue(1), v.maxValue(MAX_PLAYERS)),
  /** Players taking part / answering this round (ready list, G-38). */
  participants: v.array(PlayerIdSchema),
  answerStartsAt: TimestampSchema,
  endsAt: TimestampSchema,
  /** Who has pressed Ready (G-38). */
  ready: v.array(PlayerIdSchema),
  /**
   * The player a "[player]" question is about (G-51, Q-10) — the phone puts their name in place of
   * the token. null for a regular question.
   */
  subjectId: v.nullable(PlayerIdSchema),
});

/**
 * Which reveal step this is (G-50), named by POSITION, not by wording: `bottom` = the last place,
 * `top` = place 1. The words ("Least likely" / "Least", …) depend on the question's label set and
 * are looked up on the phone (shared/questionLabels.ts `placeLabel`), so these ids fit every set.
 */
export const RevealStepKindSchema = v.picklist(['bottom', 'third', 'second', 'top']);

export const DrinkRuleSchema = v.strictObject({
  action: v.picklist(DRINK_ACTIONS),
  sips: v.pipe(v.number(), v.integer(), v.minValue(1), v.maxValue(MAX_SIPS)),
});

export const RevealStepSchema = v.strictObject({
  kind: RevealStepKindSchema,
  /** Shared place of everyone in this step ("1, 1, 3" — S-4). */
  place: v.pipe(v.number(), v.integer(), v.minValue(1)),
  playerIds: v.pipe(v.array(PlayerIdSchema), v.minLength(1)),
  /**
   * The drinking rule announced with this place (D-1…D-9): drawn by the server once, from the range
   * of this step's kind (shared/drinkRules.ts). null is kept for a possible non-drinking mode; the
   * current rules always fill it.
   */
  rule: v.nullable(DrinkRuleSchema),
});

export const RankingEntrySchema = v.strictObject({
  playerId: PlayerIdSchema,
  place: v.pipe(v.number(), v.integer(), v.minValue(1)),
});

export const ResultOutcomeSchema = v.picklist([
  'ranked', // ≥ MIN_ANSWERS_FOR_RANKING answers
  'notEnoughAnswers', // 1 answer (S-7)
  'nobodyAnswered', // 0 answers (S-5)
]);

const RESULTS_COMMON = {
  roundId: RoundIdSchema,
  answerCount: v.pipe(v.number(), v.integer(), v.minValue(0)),
  revealStartsAt: TimestampSchema,
  /** = revealStartsAt when there is nothing to reveal (shared/reveal.ts revealEndsAt). */
  revealEndsAt: TimestampSchema,
};

/**
 * Results of one round. Votes stay secret: PLACES ONLY — no points, no vote counts, no average spot
 * (S-6). A variant on `outcome`: ranking / noVotes / steps exist ONLY for 'ranked'.
 */
export const RoundResultsSchema = v.variant('outcome', [
  v.strictObject({
    ...RESULTS_COMMON,
    outcome: v.literal('ranked'),
    /**
     * Everyone placed by at least one voter, best place first. In Spotlight that is everyone shown.
     * When `noVotes` is null, only the revealed places (1st–3rd) are listed (S-8 privacy).
     */
    ranking: v.pipe(v.array(RankingEntrySchema), v.minLength(1)),
    /**
     * Shown players nobody placed (partial rankings only — always [] in Spotlight), labelled
     * "No votes". null = withheld: a partial ranking with fewer than MIN_ANSWERS_FOR_NO_VOTES_LIST
     * answers shows only the reveal (S-8).
     */
    noVotes: v.nullable(v.array(PlayerIdSchema)),
    /** Reveal order: bottom → 3rd → 2nd → top; no bottom step in a partial ranking (G-50). */
    steps: v.pipe(v.array(RevealStepSchema), v.minLength(1)),
  }),
  v.strictObject({ ...RESULTS_COMMON, outcome: v.literal('notEnoughAnswers') }),
  v.strictObject({ ...RESULTS_COMMON, outcome: v.literal('nobodyAnswered') }),
]);

/** A "That's me" request as the host sees it (G-44). */
export const PublicReclaimSchema = v.strictObject({
  requestId: RequestIdSchema,
  targetPlayerId: PlayerIdSchema,
  nickname: v.string(),
  presetId: PresetIdSchema,
  createdAt: TimestampSchema,
  expiresAt: TimestampSchema,
});

const YouSchema = v.strictObject({ playerId: PlayerIdSchema });

const SNAPSHOT_COMMON = {
  key: GameKeySchema,
  gameId: GameIdSchema,
  /** null = host role vacant (nobody online to take it over). */
  hostId: v.nullable(PlayerIdSchema),
  settings: SettingsSchema,
  players: v.array(PublicPlayerSchema),
  /** Pending "That's me" requests — host only; always [] for other players. */
  reclaims: v.array(PublicReclaimSchema),
};

/**
 * Everything one phone needs to render its current screen (sent in `welcome`).
 * Per-viewer: `you` and (host only) `reclaims` differ between phones.
 * A variant on `phase`, so every phase carries exactly the fields it can have.
 */
export const SnapshotSchema = v.variant('phase', [
  v.strictObject({
    ...SNAPSHOT_COMMON,
    phase: v.literal('LOBBY'),
    you: YouSchema,
  }),
  v.strictObject({
    ...SNAPSHOT_COMMON,
    phase: v.literal('QUESTION'),
    /** Too few active players (G-42): only blocks the host's Next after this round. */
    paused: v.boolean(),
    you: v.strictObject({
      playerId: PlayerIdSchema,
      /** Already pressed Ready this round → show the waiting screen, not the ranking again. */
      submitted: v.boolean(),
    }),
    round: PublicRoundSchema,
  }),
  v.strictObject({
    ...SNAPSHOT_COMMON,
    phase: v.literal('RESULTS'),
    paused: v.boolean(),
    you: YouSchema,
    round: PublicRoundSchema,
    results: RoundResultsSchema,
  }),
  v.strictObject({
    ...SNAPSHOT_COMMON,
    phase: v.literal('ENDED'),
    endReason: EndReasonSchema,
    you: YouSchema,
    /** Reserved for the Game Over summary (GAME_DESCRIPTION §5.4, U3) — null until decided. */
    summary: v.null(),
  }),
]);

// ── Error codes ─────────────────────────────────────────────────────────────

/** Every error code except NAME_TAKEN, which has its own message shape (reclaimPlayerId). */
const OTHER_ERROR_CODES = [
  'OUTDATED_CLIENT', // phone older than server → reload once
  'SERVER_UPDATING', // phone newer than server → retry with backoff, no reload
  'NOT_FOUND', // unknown game / unknown token without nickname / gameId mismatch / new join to ended game
  'GAME_FULL', // G-13
  'INVALID_NICKNAME', // G-1
  'NOT_ALLOWED', // wrong phase, not host, not identified, …
  'NOT_ENOUGH_PLAYERS', // start / switching to Podium with too few active players (G-21, G-24)
  'PAUSED', // advance while too few players are active (G-42)
  'TOO_EARLY', // submit before answering opens, advance before the reveal ends: the phone's clock is off
  'INVALID', // message failed validation
  'RECLAIM_UNAVAILABLE', // target came back, left, or already has a pending request
  'LEFT', // this phone's player left the game (G-41)
  'REMOVED', // this phone's player was removed (G-43)
  'REPLACED', // sent right before closing a replaced socket (G-18)
  'RECLAIMED', // this phone's token was superseded: "That's me" moved the player to another phone (G-44)
  'NOT_ENOUGH_QUESTIONS', // start: the pool can't fill the game length (G-23 safety net — the bank keeps 35 Default questions)
  'CREATE_FAILED', // HTTP POST /api/games: no free game key found after the retries
] as const;

export const ErrorCodeSchema = v.picklist([
  'NAME_TAKEN', // G-14 (may carry reclaimPlayerId)
  ...OTHER_ERROR_CODES,
]);

// ── Client → server ─────────────────────────────────────────────────────────
// strictObject everywhere: unknown fields in untrusted input are rejected.

/** The profile a phone joins with (explicit Join tap only). */
export const JoinProfileSchema = v.strictObject({
  nickname: NicknameInputSchema,
  presetId: PresetIdSchema,
});

/**
 * No protocolVersion here: the phone puts it in the WebSocket URL (`/ws/KEY?v=N`), so the version
 * is known — and checked — when the socket opens, before any message (CLAUDE.md §4).
 */
export const HelloMessageSchema = v.strictObject({
  type: v.literal('hello'),
  /** The phone's own token for this game key, saved before sending (CLAUDE.md §3). */
  token: TokenSchema,
  /** The game this phone last saw under this key — mismatch → NOT_FOUND. */
  gameId: v.exactOptional(GameIdSchema),
  /** ONLY on an explicit Join tap, never on automatic reconnects (CLAUDE.md §5). */
  join: v.exactOptional(JoinProfileSchema),
});

export const ReclaimMessageSchema = v.strictObject({
  type: v.literal('reclaim'),
  playerId: PlayerIdSchema,
  /** The requester phone's own new token (saved first); becomes the player's on approval. */
  token: TokenSchema,
  nickname: NicknameInputSchema,
  presetId: PresetIdSchema,
});

export const ClientMessageSchema = v.variant('type', [
  HelloMessageSchema,
  v.strictObject({
    type: v.literal('updateProfile'),
    nickname: v.exactOptional(NicknameInputSchema),
    presetId: v.exactOptional(PresetIdSchema),
  }),
  /**
   * Host, lobby only (G-20, G-22, G-24): the WHOLE desired settings (idempotent; mirrors
   * settingsChanged). Switching to Podium needs PODIUM_MIN_PLAYERS active players (NOT_ALLOWED).
   */
  v.strictObject({ type: v.literal('setSettings'), settings: SettingsSchema }),
  v.strictObject({ type: v.literal('start') }),
  v.strictObject({
    type: v.literal('submit'),
    roundId: RoundIdSchema,
    /** The top `round.spots` places, best first — distinct shown players (checked by the engine). */
    ranking: v.pipe(v.array(PlayerIdSchema), v.minLength(1), v.maxLength(MAX_PLAYERS)),
  }),
  v.strictObject({ type: v.literal('advance'), roundId: RoundIdSchema }),
  v.strictObject({ type: v.literal('end') }),
  v.strictObject({ type: v.literal('leave') }),
  v.strictObject({ type: v.literal('removePlayer'), playerId: PlayerIdSchema }),
  ReclaimMessageSchema,
  v.strictObject({ type: v.literal('cancelReclaim') }),
  v.strictObject({
    type: v.literal('answerReclaim'),
    requestId: RequestIdSchema,
    approve: v.boolean(),
  }),
  v.strictObject({ type: v.literal('timeSync'), t0: v.number() }),
]);

/** Every client message type — kept equal to ClientMessage['type'] by the check below. */
export const CLIENT_MESSAGE_TYPES = [
  'hello',
  'updateProfile',
  'setSettings',
  'start',
  'submit',
  'advance',
  'end',
  'leave',
  'removePlayer',
  'reclaim',
  'cancelReclaim',
  'answerReclaim',
  'timeSync',
] as const;
export const ClientMessageTypeSchema = v.picklist(CLIENT_MESSAGE_TYPES);

// ── Server → client ─────────────────────────────────────────────────────────

/** Which request an error answers, so the phone can tell a failed Next from a failed submit. */
const ERROR_FOR = v.exactOptional(ClientMessageTypeSchema);

/** A variant on `code`: only NAME_TAKEN may carry reclaimPlayerId. */
export const ErrorMessageSchema = v.variant('code', [
  v.strictObject({
    type: v.literal('error'),
    code: v.literal('NAME_TAKEN'),
    for: ERROR_FOR,
    /** The name belongs to an OFFLINE player → the joiner may offer "That's me" (G-14, G-44). */
    reclaimPlayerId: v.exactOptional(PlayerIdSchema),
  }),
  v.strictObject({
    type: v.literal('error'),
    code: v.picklist(OTHER_ERROR_CODES),
    for: ERROR_FOR,
  }),
]);

export const ServerMessageSchema = v.variant('type', [
  v.strictObject({
    type: v.literal('welcome'),
    playerId: PlayerIdSchema,
    gameId: GameIdSchema,
    snapshot: SnapshotSchema,
    serverTime: TimestampSchema,
  }),
  v.strictObject({ type: v.literal('playerJoined'), player: PublicPlayerSchema }),
  v.strictObject({
    type: v.literal('playerLeft'),
    playerId: PlayerIdSchema,
    reason: v.picklist(['left', 'removed']),
  }),
  v.strictObject({
    type: v.literal('playerConnection'),
    playerId: PlayerIdSchema,
    online: v.boolean(),
    offlineSince: v.nullable(TimestampSchema),
  }),
  v.strictObject({
    type: v.literal('playerUpdated'),
    playerId: PlayerIdSchema,
    nickname: v.string(),
    avatar: AvatarSchema,
  }),
  v.strictObject({ type: v.literal('settingsChanged'), settings: SettingsSchema }),
  /**
   * To the leaving phone only: the leave went through (G-41). The phone keeps its token until this
   * arrives — if the connection drops first, a reconnect with that token gets LEFT instead.
   */
  v.strictObject({ type: v.literal('leftGame') }),
  /** A new round. Late joiners listed in round.participants are no longer waiting. */
  v.strictObject({ type: v.literal('roundStarted'), round: PublicRoundSchema }),
  v.strictObject({
    type: v.literal('playerReady'),
    roundId: RoundIdSchema,
    playerId: PlayerIdSchema,
  }),
  v.strictObject({ type: v.literal('roundResults'), results: RoundResultsSchema }),
  v.strictObject({ type: v.literal('hostChanged'), hostId: v.nullable(PlayerIdSchema) }),
  v.strictObject({
    type: v.literal('paused'),
    needed: v.pipe(v.number(), v.integer(), v.minValue(1)),
  }),
  v.strictObject({ type: v.literal('resumed') }),
  v.strictObject({ type: v.literal('reclaimPending'), requestId: RequestIdSchema }),
  v.strictObject({ type: v.literal('reclaimRequested'), request: PublicReclaimSchema }),
  v.strictObject({ type: v.literal('reclaimClosed'), requestId: RequestIdSchema }),
  v.strictObject({ type: v.literal('reclaimResult'), approved: v.boolean() }),
  v.strictObject({
    type: v.literal('gameEnded'),
    reason: EndReasonSchema,
    /** Reserved for the Game Over summary (GAME_DESCRIPTION §5.4, U3) — null until decided. */
    summary: v.null(),
  }),
  v.strictObject({ type: v.literal('timeSync'), t0: v.number(), serverTime: TimestampSchema }),
  ErrorMessageSchema,
]);

